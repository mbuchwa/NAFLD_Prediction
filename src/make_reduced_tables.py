"""
make_reduced_tables.py
======================
Builds the "reduced-feature models" table (former Table 10): each model trained
on only the top-3 SHAP biomarkers per task, compared side-by-side with the
full-biomarker model. Reads the *_shap_selected_*_metrics.json written by the
SHAP_SELECTED=True evaluation run.

Place in:  src/            Run from:  src/  ->  python make_reduced_tables.py
Output:    outputs/results/tables_reduced.tex

The comparison the table makes per task and cohort:
    Model            AUROC (full)      AUROC (3 features)      Delta
so a reviewer sees directly how much discrimination is retained by the minimal
panel. Sensitivity/specificity of the reduced model are added below AUROC.
"""

import glob
import json
from pathlib import Path

import numpy as np

OUT = Path('outputs/results/tables_reduced.tex')

TASK_META = {
    'fibrosis':  ('Moderate Fibrosis', r'F0/1 vs.\ F2/3/4', ['Platelets', 'ASAT', 'MCV']),
    'two_stage': ('Severe Fibrosis',   r'F0/1/2 vs.\ F3/4', ['Platelets', 'INR', 'MCV']),
    'cirrhosis': ('Cirrhosis',         r'F0/1/2/3 vs.\ F4', ['Platelets', 'INR', 'MCV']),
    'three_stage': ('Three Stage',     r'F0/1 / F2/3 / F4', ['Platelets', 'MCV', 'Quick']),
}
BASE_MODELS = ['light_gbm', 'xgb', 'rf', 'svm', 'vi_bnn']
MODEL_LABEL = {'light_gbm': 'LightGBM', 'xgb': 'XGBoost', 'rf': 'Random Forest',
               'svm': 'SVM', 'vi_bnn': 'VI-BNN'}
COHORT = {'internal_test': 'UMM', 'prospective': 'MAINZ'}
SUFFIX = '_shap_selected'


def load():
    recs = {}
    for path in glob.glob('outputs/**/*_metrics.json', recursive=True):
        try:
            r = json.load(open(path))
        except Exception:
            continue
        recs[(r.get('model_name'), r.get('classification_type'), r.get('split'))] = r
    return recs


def fmt(v, lo=None, hi=None, nd=3, pct=False):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return '--'
    s = f'{v * (100 if pct else 1):.{nd}f}'
    if lo is not None and hi is not None and not (np.isnan(lo) or np.isnan(hi)):
        s += f' ({lo * (100 if pct else 1):.{nd}f}--{hi * (100 if pct else 1):.{nd}f})'
    return s


def auroc(rec):
    if not rec:
        return None
    b = rec.get('binary')
    return b['auroc'] if b else None


def main():
    recs = load()
    if not recs:
        print('No *_metrics.json found - run the SHAP_SELECTED=True evaluation first.')
        return

    n_reduced = sum(1 for (m, _, _) in recs if m and m.endswith(SUFFIX))
    if n_reduced == 0:
        print('No *_shap_selected_* records found. Did you run run_all_experiments.py '
              'with SHAP_SELECTED=True?')
        return
    print(f'Found {n_reduced} reduced-model records.')

    out = ['% ' + '=' * 62,
           '%  REDUCED-FEATURE MODELS (top-3 SHAP biomarkers per task)',
           '%  auto-generated by make_reduced_tables.py',
           '% ' + '=' * 62, '']

    for task, (name, defn, feats) in TASK_META.items():
        if task == 'three_stage':
            continue  # ordinal metrics handled separately; keep binary tasks here
        panel = feats
        for split, coh in COHORT.items():
            rows = []
            for i, m in enumerate(BASE_MODELS):
                full = recs.get((m, task, split))
                red = recs.get((m + SUFFIX, task, split))
                a_full, a_red = auroc(full), auroc(red)
                if a_full is None and a_red is None:
                    continue
                delta = (a_red - a_full) if (a_full is not None and a_red is not None) else None
                delta_txt = (f'{delta:+.3f}' if delta is not None else '--')
                # sensitivity / specificity of the reduced model
                rb = red.get('binary') if red else None
                sens = fmt(rb['operating_metrics']['Sensitivity'], pct=True, nd=1) if rb else '--'
                spec = fmt(rb['operating_metrics']['Specificity'], pct=True, nd=1) if rb else '--'
                sh = r'\rowcolor{gray!10} ' if i % 2 == 0 else ''
                rows.append(f'        {sh}{MODEL_LABEL[m]} & {fmt(a_full)} & {fmt(a_red)} '
                            f'& {delta_txt} & {sens} & {spec} \\\\')
            if not rows:
                continue
            out.append(
                '\\begin{table*}[htbp]\n    \\centering\n'
                f'    \\caption{{\\small{{Reduced-feature models for the \\textit{{{name}}} task '
                f'({defn}) on the \\textit{{{coh}}} cohort. Each model was retrained on only the three '
                f'most influential biomarkers ({", ".join(panel)}). AUROC of the full-biomarker model is '
                'shown alongside the reduced model; $\\Delta$AUROC is the change from full to reduced. '
                'Sensitivity and specificity refer to the reduced model at the validation-fixed threshold.}}\n'
                f'    \\label{{tab:reduced_{task}_{coh.lower()}}}\n'
                '    \\begin{tabular}{lccccc}\n        \\toprule\n'
                '        \\textbf{Model} & \\textbf{AUROC (full)} & \\textbf{AUROC (3 feat.)} '
                '& \\textbf{$\\Delta$AUROC} & \\textbf{Sens.\\ (\\%)} & \\textbf{Spec.\\ (\\%)}\\\\\n'
                '        \\midrule')
            out += rows
            out.append('        \\bottomrule\n    \\end{tabular}\n\\end{table*}\n')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(out))
    print(f'Reduced-model tables -> {OUT}')


if __name__ == '__main__':
    main()