"""
make_latex_tables.py
====================
Reads every <model>_<task>_metrics.json written by evaluate_performance and
emits publication-ready LaTeX tables, including the FIB-4 comparator row.

Place in:  src/            Run from:  src/  ->  python make_latex_tables.py
Output:    outputs/results/tables_revised.tex

Models whose probability outputs are not calibrated to [0,1] (AUROC < 0.5 with
degenerate specificity) are reported in the ordinal table only and excluded from
the discrimination tables, with a warning; fix the softmax in the corresponding
make_ensemble_preds_* function to include them.
"""

import glob
import json
from pathlib import Path

import numpy as np

OUT = Path('outputs/results/tables_revised.tex')

TASK_META = {
    'fibrosis':  ('Moderate Fibrosis', r'F0/1 vs.\ F2/3/4'),
    'two_stage': ('Severe Fibrosis',   r'F0/1/2 vs.\ F3/4'),
    'cirrhosis': ('Cirrhosis',         r'F0/1/2/3 vs.\ F4'),
}
MODEL_LABEL = {
    'svm': 'SVM', 'rf': 'Random Forest', 'xgb': 'XGBoost', 'light_gbm': 'LightGBM',
    'ffn': 'MLP', 'tab_transformer': 'TabTransformer', 'vi_bnn': 'VI-BNN',
    'gandalf': 'GANDALF',
}
MODEL_ORDER = list(MODEL_LABEL)
COHORT = {'internal_test': 'UMM', 'prospective': 'MAINZ'}


def load():
    recs = {}
    for path in glob.glob('outputs/**/*_metrics.json', recursive=True):
        try:
            r = json.load(open(path))
        except Exception:
            continue
        recs[(r.get('model_name'), r.get('classification_type'), r.get('split'))] = r
    return recs


def fmt(v, lo=None, hi=None, pct=False, nd=2):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return '--'
    s = f'{v * (100 if pct else 1):.{nd}f}'
    if lo is not None and hi is not None and not (np.isnan(lo) or np.isnan(hi)):
        s += f' ({lo * (100 if pct else 1):.{nd}f}--{hi * (100 if pct else 1):.{nd}f})'
    return s


def binary_row(label, b, shade):
    if not b:
        return None
    o, c = b['operating_metrics'], b['operating_cis']
    cells = [fmt(b['auroc'], b['auroc_ci_lower'], b['auroc_ci_upper'], nd=3)]
    cells += [fmt(o[m], c[m][0], c[m][1], pct=True) for m in
              ['Sensitivity', 'Specificity', 'PPV', 'NPV']]
    sh = r'\rowcolor{gray!10} ' if shade else ''
    return f'        {sh}{label} & ' + ' & '.join(cells) + r' \\'


def is_degenerate(b):
    """Uncalibrated probability output: AUROC below chance with 0/1 operating point."""
    if not b:
        return False
    spec = b['operating_metrics'].get('Specificity')
    return b['auroc'] < 0.5 and (spec == 0.0 or np.isnan(spec))


def main():
    recs = load()
    if not recs:
        print('No *_metrics.json found - run the evaluation sweep first.')
        return

    excluded = set()
    for (m, t, s), r in recs.items():
        if t != 'three_stage' and is_degenerate(r.get('binary')):
            excluded.add(m)
    if excluded:
        print('WARNING: excluded from discrimination tables (uncalibrated outputs): '
              + ', '.join(sorted(MODEL_LABEL.get(m, m) for m in excluded)))

    out = ['% ' + '=' * 62,
           '%  REVISED RESULT TABLES - single-pass held-out evaluation',
           '%  auto-generated by make_latex_tables.py - do not edit by hand',
           '% ' + '=' * 62, '']

    for task, (name, defn) in TASK_META.items():
        for split, coh in COHORT.items():
            rows, fib4, apri = [], None, None
            n = prev = None
            i = 0
            for m in MODEL_ORDER:
                r = recs.get((m, task, split))
                if not r or m in excluded:
                    continue
                n, prev = r.get('n_samples'), r.get('positive_prevalence')
                fib4 = fib4 or r.get('fib4')
                apri = apri or r.get('apri')
                row = binary_row(MODEL_LABEL[m], r.get('binary'), i % 2 == 0)
                if row:
                    rows.append(row)
                    i += 1
            if not rows:
                continue

            prev_txt = f'{prev * 100:.1f}\\%' if prev is not None else '--'
            out.append(
                '\\begin{table*}[htbp]\n    \\centering\n'
                f'    \\caption{{\\small{{Discrimination and operating-point performance of the ensemble models\n'
                f'    for the \\textit{{{name}}} task ({defn}) on the \\textit{{{coh}}} cohort\n'
                f'    (n={n}; prevalence of the positive class {prev_txt}). Point estimates with 95\\% bootstrap\n'
                '    confidence intervals (1{,}000 resamples). Sensitivity, specificity, PPV and NPV are evaluated\n'
                '    at a single operating threshold fixed on the validation partition (Youden index); FIB-4 is\n'
                '    evaluated at its established clinical cut-off. Arrows indicate that higher values are better.}}\n'
                f'    \\label{{tab:{task}_{coh.lower()}}}\n'
                '    \\begin{tabular}{lccccc}\n        \\toprule\n'
                '        \\textbf{Model} & \\textbf{AUROC} $\\uparrow$ & \\textbf{Sens.\\ (\\%)} $\\uparrow$ '
                '& \\textbf{Spec.\\ (\\%)} $\\uparrow$ & \\textbf{PPV (\\%)} $\\uparrow$ '
                '& \\textbf{NPV (\\%)} $\\uparrow$\\\\\n        \\midrule')
            out += rows
            out.append('        \\midrule')
            f4 = binary_row(f"FIB-4 (cut-off {fib4['threshold']:.2f})", fib4, False) if fib4 else \
                 '        FIB-4 & \\textit{[not available]} & & & & \\\\'
            out.append(f4)
            fa = binary_row(f"APRI (cut-off {apri['threshold']:.2f})", apri, True) if apri else \
                 '        \\rowcolor{gray!10} APRI & \\textit{[not available]} & & & & \\\\'
            out.append(fa)
            out.append('        \\bottomrule\n    \\end{tabular}\n\\end{table*}\n')

    # ---- three-stage / ordinal ----
    o_rows, f4_3, a4_3 = [], {}, {}
    n_int = n_ext = None
    i = 0
    for m in MODEL_ORDER:
        ri = recs.get((m, 'three_stage', 'internal_test'))
        re_ = recs.get((m, 'three_stage', 'prospective'))
        if not ri and not re_:
            continue
        if ri:
            n_int = ri.get('n_samples')
            f4_3['UMM'] = ri.get('fib4') or f4_3.get('UMM')
            a4_3['UMM'] = ri.get('apri') or a4_3.get('UMM')
        if re_:
            n_ext = re_.get('n_samples')
            f4_3['MAINZ'] = re_.get('fib4') or f4_3.get('MAINZ')
            a4_3['MAINZ'] = re_.get('apri') or a4_3.get('MAINZ')

        def cells(r):
            if not r:
                return ['--', '--', '--']
            p = (r.get('pooled_rubin') or {}).get('ACC', {})
            o = r.get('ordinal') or {}
            return [fmt(p.get('estimate'), p.get('ci_lower'), p.get('ci_upper'), pct=True),
                    fmt(o.get('cohen_kappa_linear'), nd=3), fmt(o.get('mae'), nd=3)]

        sh = r'\rowcolor{gray!10} ' if i % 2 == 0 else ''
        o_rows.append(f'        {sh}{MODEL_LABEL[m]} & ' + ' & '.join(cells(ri) + cells(re_)) + r' \\')
        i += 1

    if o_rows:
        out.append(
            '\\begin{table*}[htbp]\n    \\centering\n'
            '    \\caption{\\small{Ordinal-aware performance for the \\textit{Three Stage} task '
            '(F0/1 vs.\\ F2/3 vs.\\ F4).\n'
            f'    UMM n={n_int}, MAINZ n={n_ext}. Accuracy is pooled across the m=10 imputations '
            "(Rubin's rules, 95\\% CI).\n"
            "    Linearly weighted Cohen's $\\kappa$ and the mean absolute error (MAE) in fibrosis stages penalise\n"
            '    distant misclassifications more strongly than adjacent ones. Owing to the small intermediate class,\n'
            '    the UMM estimates are exploratory.}}\n'
            '    \\label{tab:three_stage}\n'
            '    \\begin{tabular}{lcccccc}\n        \\toprule\n'
            '        & \\multicolumn{3}{c}{\\textbf{UMM}} & \\multicolumn{3}{c}{\\textbf{MAINZ}}\\\\\n'
            '        \\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\n'
            '        \\textbf{Model} & \\textbf{ACC (\\%)} $\\uparrow$ & \\textbf{$\\kappa_{lin}$} $\\uparrow$ '
            '& \\textbf{MAE} $\\downarrow$ & \\textbf{ACC (\\%)} $\\uparrow$ '
            '& \\textbf{$\\kappa_{lin}$} $\\uparrow$ & \\textbf{MAE} $\\downarrow$\\\\\n        \\midrule')
        out += o_rows
        out.append('        \\midrule')

        def f4cells(f):
            if not f:
                return ['--', '--', '--']
            return [fmt(f.get('accuracy'), pct=True), fmt(f.get('cohen_kappa_linear'), nd=3),
                    fmt(f.get('mae'), nd=3)]
        out.append('        FIB-4 & ' + ' & '.join(f4cells(f4_3.get('UMM')) +
                                                   f4cells(f4_3.get('MAINZ'))) + r' \\')
        out.append('        \\rowcolor{gray!10} APRI & ' + ' & '.join(f4cells(a4_3.get('UMM')) +
                                                   f4cells(a4_3.get('MAINZ'))) + r' \\')
        out.append('        \\bottomrule\n    \\end{tabular}\n\\end{table*}\n')

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(out))
    print(f'LaTeX tables -> {OUT}')


if __name__ == '__main__':
    main()